#!/usr/bin/env python3
"""Generate bounded C++ and embedded EEL conversions from the module catalog."""
import argparse,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def generated():
    catalog=json.loads((ROOT/'modules/catalog.json').read_text())
    params={p['engineKind']:p for p in catalog['parameters'] if 0<=p['engineKind']<=25}
    if set(params)!=set(range(26)):raise ValueError('native parameter identities must be complete and unique')
    modules=[m for m in catalog['modules'] if 1<=m['engineType']<=6]
    by_id={p['id']:p for p in catalog['parameters']}
    def cpp_expr(items,default):return ''.join(f'{condition} ? {value} : ' for condition,value in items)+str(default)
    def predicate(k):return params[k]['valueType'] in ('enum','toggle') or params[k].get('snapshotSwitch')=='discrete'
    cpp='''// Generated by scripts/generate-parameters.py; edit modules/catalog.json.
#pragma once
#include <algorithm>
#include <cmath>
namespace performance {
'''
    cpp+='constexpr int parameterCount(int type) { return '+cpp_expr([(f'type=={m["engineType"]}',len(m['parameters'])) for m in modules],0)+'; }\n'
    rows=[(f'type=={m["engineType"]} && row=={row}',by_id[id]['engineKind']) for m in modules for row,id in enumerate(m['parameters'])]
    cpp+='constexpr int parameterKind(int type,int row) { return '+cpp_expr(rows,-1)+'; }\n'
    for name,test in [('discrete',predicate),('binned',lambda k:params[k]['normalizedConversion']=='equal_bins'),('phraseKind',lambda k:params[k]['id'] in next(m for m in catalog['modules'] if m['typeId']=='phrase_parameters')['parameters'])]:
        cpp+=f'constexpr bool {name}(int kind) {{ return '+ ' || '.join(f'kind=={k}' for k in params if test(k))+'; }\n'
    cpp+='struct Parameter { double low,high,step; int conversion; };\nstatic constexpr Parameter parameters[]={\n'
    for k in sorted(params):
        p=params[k]
        conv={'linear_quantized':0,'equal_bins':1,'log_ratio':2,'linear_continuous':3}[p['normalizedConversion']]
        cpp+=f'  {{{p["min"]},{p["max"]},{p["step"]},{conv}}}, // {k}: {p["id"]}\n'
    cpp+='''};
inline double physical(int kind,double x) {
  if(kind<0 || kind>=26) return 0;
  const auto &p=parameters[kind]; x=std::max(0.,std::min(1.,x));
  if(p.conversion==2) return std::pow(2.,2*x-1);
  if(p.conversion==3) return p.low+(p.high-p.low)*x;
  if(p.conversion==1) return std::min(p.high,std::floor(x*(p.high+1)));
  return std::max(p.low,std::min(p.high,std::floor((p.low+(p.high-p.low)*x)/p.step+.5)*p.step));
}
inline double normalized(int kind,double v) {
  if(kind<0 || kind>=26) return 0;
  const auto &p=parameters[kind];
  const double n=p.conversion==2 ? (std::log2(v<=0?1:v)+1)/2
      : p.conversion==1 ? (v+.5)/(p.high+1) : (v-p.low)/(p.high-p.low);
  return std::max(0.,std::min(1.,n));
}
} // namespace performance
'''
    def eel_lookup(field,default):return cpp_expr([(f'kind=={k}',p[field]) for k,p in params.items() if p[field]!=default],default)
    eel='// Generated bounds: scripts/generate-parameters.py / modules/catalog.json\n'
    for name,field,default in [('param_min','min',0),('param_max','max',127),('param_step','step',1)]:eel+=f'function {name}(kind)\n({eel_lookup(field,default)};);\n'
    conv=lambda name:' || '.join(f'kind=={k}' for k,p in params.items() if p['normalizedConversion']==name)
    scale=f'''function param_scale(kind,pos)
local(lo,hi,step,v)
(
  lo=param_min(kind);hi=param_max(kind);step=param_step(kind);pos=max(0,min(1,pos));
  {conv('log_ratio')} ? pow(2,2*pos-1) :
  {conv('linear_continuous')} ? lo+(hi-lo)*pos :
  {conv('equal_bins')} ? min(hi,floor(pos*(hi+1))) : (
    v=lo+(hi-lo)*pos;max(lo,min(hi,floor(v/step+.5)*step));
  );
);
function param_normalize(kind,v)
local(lo,hi,n)
(
  lo=param_min(kind);hi=param_max(kind);
  {conv('log_ratio')} ? n=(log(v<=0?1:v)/log(2)+1)/2 :
  {conv('equal_bins')} ? n=(v+.5)/(hi+1) : n=(v-lo)/(hi-lo);
  max(0,min(1,n));
);
'''
    source=(ROOT/'midi_human_looper.jsfx').read_text()
    source=re.sub(r'(?:\/\/ Generated bounds:[^\n]*\n)?function param_min\(kind\).*?(?=function param_name)',lambda _:eel,source,flags=re.S)
    source=re.sub(r'function param_scale\(kind,pos\).*?(?=function param_extension_reset)',lambda _:scale,source,flags=re.S)
    return {ROOT/'headless/parameter_registry.hpp':cpp,ROOT/'midi_human_looper.jsfx':source}

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    stale=[]
    for path,text in generated().items():
        if path.read_text()!=text:
            if args.check:stale.append(str(path.relative_to(ROOT)))
            else:path.write_text(text)
    if stale:p.exit(1,'Stale generated contract: '+', '.join(stale)+'\n')
if __name__=='__main__':main()
